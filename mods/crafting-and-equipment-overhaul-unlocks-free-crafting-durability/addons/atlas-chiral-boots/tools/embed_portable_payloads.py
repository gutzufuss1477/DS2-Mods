"""Embed the exact confirmed payload bytes; refuse altered authoring inputs."""
from pathlib import Path
import hashlib, json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'release/test15-api/atlas_chiral'
OUT = ROOT / 'build/api/embedded_payload.cpp'

def main():
    proof = json.loads((ROOT/'evidence/test15-install.json').read_text())
    expected = {n: h for n, h in proof['payloadSHA256'].items() if n.endswith('.bin')}
    assert set(expected) == {'geometry-table.bin', 'geometry-append.bin', 'graph-addon.bin', 'links-delta.bin'}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    payloads = []
    for name, digest in sorted(expected.items()):
        data = (SOURCE/name).read_bytes()
        assert hashlib.sha256(data).hexdigest() == digest, name
        payloads.append((name, digest, data))
    with OUT.open('w', encoding='ascii', newline='\n') as f:
        f.write('// Generated by tools/embed_portable_payloads.py. Do not edit.\n#include "embedded_payload.hpp"\nnamespace {\n')
        for i, (name, digest, data) in enumerate(payloads):
            f.write(f'alignas(16) const unsigned char data{i}[] =\n')
            for j in range(0, len(data), 256):
                f.write('"' + ''.join(f'\\x{x:02x}' for x in data[j:j+256]) + '"\n')
            f.write(f';\nstatic_assert(sizeof(data{i})-1 == {len(data)}, "payload size");\n')
        f.write('const EmbeddedPayload payloads[] = {\n')
        for i, (_, digest, data) in enumerate(payloads):
            f.write(f'{{data{i}, {len(data)}, "{digest}"}},\n')
        f.write('};\nbool sameName(const wchar_t*a,const wchar_t*b){if(!a)return false;while(*a&&*a==*b){++a;++b;}return *a==*b;}\n}\n')
        f.write('const EmbeddedPayload* findEmbeddedPayload(const wchar_t* name){\n')
        for i, (name, _, _) in enumerate(payloads):
            f.write(f' if(sameName(name,L"{name}"))return &payloads[{i}];\n')
        f.write(' return nullptr;\n}\n')
    report = {'source': 'confirmed Test15 payloads', 'totalBytes': sum(len(d) for _, _, d in payloads),
              'payloads': {n: {'bytes': len(d), 'sha256': h} for n, h, d in payloads}}
    (ROOT/'evidence/test16-embedded-inputs.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report, indent=2))

if __name__ == '__main__': main()
