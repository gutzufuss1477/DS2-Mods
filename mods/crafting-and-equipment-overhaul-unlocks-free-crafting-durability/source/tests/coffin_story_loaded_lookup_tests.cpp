#include "../src/coffin_story_loaded_lookup.hpp"
#include <unordered_map>
#include <cstring>
#include <cstdio>
using namespace coffin_story;
int main(){
 unsigned checks=0,errors=0;
 auto ck=[&](bool valid,const char*name){++checks;if(!valid){++errors;std::printf("FAIL %s\n",name);}};
 constexpr U64 image=0x140000000ull;
 constexpr U64 origGroup=0x3200000000ull, storyGroup=origGroup-0x200000ull;
 constexpr U64 normalBag=origGroup+0x01387c10ull;
 constexpr U64 origTable=0x3600000000ull, storyTable=0x3610000000ull;
 constexpr U64 storyBag=0x3400000000ull, storyEntity=storyBag+0x510ull;
 constexpr U64 components=0x3410000000ull;
 std::unordered_map<U64,U64> content;
 auto put=[&](U64 a,U64 v){content[a]=v;};
 auto reader=[&](U64 a,auto&value)->bool{
  auto at=content.find(a);if(at==content.end())return false;
  std::memcpy(&value,&at->second,sizeof(value));return true;
 };
 auto setup=[&](){
  content.clear();
  put(normalBag,image+BaggageVtableRva);
  put(normalBag+0x0c,NormalGroupId);
  put(normalBag+0x10,NormalBaggageUUID[0]);
  put(normalBag+0x18,NormalBaggageUUID[1]);
  put(normalBag+0x20,CoffinboardModelType);
  put(origGroup+0x40,NormalGroupResourceCount);
  put(origGroup+0x44,NormalGroupResourceCount);
  put(origGroup+0x48,origTable);
  put(origGroup+0x64,NormalGroupId);
  put(origTable+8ull*NormalBagIndex,normalBag);
  put(storyGroup+0x40,StoryGroupResourceCount);
  put(storyGroup+0x44,StoryGroupResourceCount);
  put(storyGroup+0x48,storyTable);
  put(storyGroup+0x64,StoryGroupId);
  put(storyTable+8ull*StoryBagIndex,storyBag);
  put(storyTable+8ull*StoryEntityIndex,storyEntity);
  put(storyBag,image+BaggageVtableRva);
  put(storyBag+0x0c,StoryGroupId);
  put(storyBag+0x10,StoryBaggageVisualUUID[0]);
  put(storyBag+0x18,StoryBaggageVisualUUID[1]);
  put(storyBag+0x20,StoryCoffinBaggageModelType);
  put(storyBag+0x28,storyEntity);
  put(storyEntity,image+EntityVtableRva);
  put(storyEntity+0x0c,StoryGroupId);
  put(storyEntity+0x10,StoryBaggageEntityUUID[0]);
  put(storyEntity+0x18,StoryBaggageEntityUUID[1]);
  put(storyEntity+0x48,11u);
  put(storyEntity+0x50,components);
 };
 setup();
 auto found=findLoaded(reader,image,normalBag);
 ck(found.ready(),"correct native direct Story Coffin entity resolved");
 ck(found.entity==storyEntity&&found.bag==storyBag,"both original resource pointers selected");
 ck(found.normalGroup==origGroup&&found.storyGroup==storyGroup,"correct group IDs and locations");
 ck(!findLoaded(reader,image,0).ready(),"null native source refused");
 ck(!findLoaded(reader,0,normalBag).ready(),"null DS2 image refused");
 ck(!findLoaded(reader,image,normalBag+8).ready(),"wrong input offset refused");
 setup();put(normalBag,image+BaggageVtableRva+1);
 ck(!findLoaded(reader,image,normalBag).ready(),"unknown stock model vtable refused");
 setup();put(normalBag+0x0c,8542u);
 ck(!findLoaded(reader,image,normalBag).ready(),"original source groupID must be 499");
 setup();put(normalBag+0x20,31u);
 ck(!findLoaded(reader,image,normalBag).ready(),"only canonical ModelType30 can arm Story fallback");
 setup();put(normalBag+0x10,NormalBaggageUUID[0]^1);
 ck(!findLoaded(reader,image,normalBag).ready(),"incorrect original UUID refused");
 setup();put(origGroup+0x40,NormalGroupResourceCount+1);
 ck(!findLoaded(reader,image,normalBag).ready(),"wrong stock group resource count refused");
 setup();put(origGroup+0x64,8542u);
 ck(!findLoaded(reader,image,normalBag).ready(),"wrong native group header ID refused");
 setup();put(origTable+8ull*NormalBagIndex,normalBag+8);
 ck(!findLoaded(reader,image,normalBag).ready(),"resource array must point exactly to canonical source");
 setup();put(storyGroup+0x40,179u);
 ck(!findLoaded(reader,image,normalBag).ready(),"truncated StoryGroup resources refused");
 setup();put(storyGroup+0x44,StoryGroupResourceCount+1u);
 ck(!findLoaded(reader,image,normalBag).ready(),"wrong StoryGroup allocation capacity refused");
 setup();put(storyGroup+0x64,499u);
 ck(!findLoaded(reader,image,normalBag).ready(),"wrong StoryGroup ID refused");
 setup();put(storyBag+0x10,StoryBaggageVisualUUID[0]^1);
 ck(!findLoaded(reader,image,normalBag).ready(),"incorrect Story baggage UUID refused");
 setup();put(storyBag+0x20,30u);
 ck(!findLoaded(reader,image,normalBag).ready(),"source Story baggage must be ModelType31");
 setup();put(storyBag+0x28,0);
 ck(!findLoaded(reader,image,normalBag).ready(),"Story baggage must point to original Story Entity");
 setup();put(storyEntity,image+EntityVtableRva+8);
 ck(!findLoaded(reader,image,normalBag).ready(),"invalid Story Entity vtable refused");
 setup();put(storyEntity+0x18,StoryBaggageEntityUUID[1]^1);
 ck(!findLoaded(reader,image,normalBag).ready(),"invalid Story Entity UUID refused");
 setup();put(storyEntity+0x48,4u);
 ck(!findLoaded(reader,image,normalBag).ready(),"incomplete Story Entity component graph refused");
 setup();put(storyEntity+0x50,0);
 ck(!findLoaded(reader,image,normalBag).ready(),"Story Entity missing component pointers refused");
 setup();content.erase(storyTable+8ull*StoryEntityIndex);
 ck(!findLoaded(reader,image,normalBag).ready(),"missing Story resource in native group fails closed");
 setup();content.erase(storyGroup+0x48);
 ck(!findLoaded(reader,image,normalBag).ready(),"unreadable StoryGroup table pointer fails closed");
 setup();
 constexpr U64 ambiguous=storyGroup+0x10000ull;
 for(U64 off:{0x40ull,0x44ull,0x48ull,0x64ull})
  put(ambiguous+off,content.at(storyGroup+off));
 ck(!findLoaded(reader,image,normalBag).ready(),"two apparently valid StoryGroup headers refused");
 setup();found=findLoaded(reader,image,normalBag);
 ck(found.ready()&&found.entity==storyEntity,"valid direct Story resource remains selectable after negatives");
 ck(StoryGroupId==8542u&&StoryBagIndex==64u&&StoryEntityIndex==46u,"Odradek exact identifiers");
 ck(GroupPageAlignment==0x10000ull && GroupScanRadius==0x2000000ull,"resource group probe strictly bounded");
 std::printf("COFFIN_LOADED_STORY_RESOURCE_ASSERTIONS %u ERRORS %u\n",checks,errors);
 return errors?1:0;
}
